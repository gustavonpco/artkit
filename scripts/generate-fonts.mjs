#!/usr/bin/env node
// Embeds the Sora variable font (latin subset, SIL OFL 1.1) as a base64 module in @artkit/core/fonts, so
// the Mouts design system typography works offline, in headless export (network blocked) and without a
// bundler, and no request ever goes to a third-party font CDN.
// Run after updating @fontsource-variable/sora: node scripts/generate-fonts.mjs
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';

const require = createRequire(import.meta.url);
const pkgDir = dirname(require.resolve('@fontsource-variable/sora/package.json'));
const pkg = JSON.parse(readFileSync(join(pkgDir, 'package.json'), 'utf8'));
const woff2 = readFileSync(join(pkgDir, 'files/sora-latin-wght-normal.woff2'));
const root = new URL('..', import.meta.url).pathname;
const outDir = join(root, 'packages/core/src/fonts');
mkdirSync(outDir, { recursive: true });

const source = `// Generated by scripts/generate-fonts.mjs from ${pkg.name}@${pkg.version}. Do not edit by hand.
// Sora, Copyright 2019 The Sora Project Authors (https://github.com/sora-xor/sora-font), SIL Open Font
// License 1.1 (see packages/core/fonts/OFL-Sora.txt). Latin subset, variable weight 100-800.

/** Base64 of the Sora variable font (woff2, latin subset). */
export const SORA_WOFF2_BASE64 =
  '${woff2.toString('base64')}';

export const SORA_UNICODE_RANGE =
  'U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD';
`;
writeFileSync(join(outDir, 'sora-data.ts'), source);
mkdirSync(join(root, 'packages/core/fonts'), { recursive: true });
copyFileSync(join(pkgDir, 'LICENSE'), join(root, 'packages/core/fonts/OFL-Sora.txt'));
console.log(`Embedded Sora (${woff2.length} bytes) into packages/core/src/fonts/sora-data.ts`);
