#!/usr/bin/env node
// Generates the diagram node icons from Lucide (ISC) as plain SVG element data, so the diagram model,
// renderer and svg exporter share them without a runtime dependency. Run after updating `lucide`:
// node scripts/generate-icons.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';

const require = createRequire(import.meta.url);
const lucide = require('lucide');
const pkg = JSON.parse(
  readFileSync(join(dirname(require.resolve('lucide/package.json')), 'package.json'), 'utf8'),
);

// Diagram icon name → Lucide icon.
const MAP = {
  database: 'Database',
  server: 'Server',
  user: 'User',
  cloud: 'Cloud',
  queue: 'Layers',
  api: 'Braces',
  mobile: 'Smartphone',
  web: 'Globe',
  lock: 'Lock',
  file: 'FileText',
  mail: 'Mail',
  settings: 'Settings',
  search: 'Search',
  chart: 'ChartColumn',
  bot: 'Bot',
  shield: 'Shield',
};
const ALLOWED = new Set(['path', 'rect', 'circle', 'ellipse', 'line', 'polyline', 'polygon']);

const entries = Object.entries(MAP).map(([name, icon]) => {
  const nodes = lucide[icon];
  if (!Array.isArray(nodes)) throw new Error(`Lucide icon ${icon} not found`);
  const elements = nodes.map(([tag, attrs]) => {
    if (!ALLOWED.has(tag)) throw new Error(`Unsupported element <${tag}> in ${icon}`);
    const clean = Object.fromEntries(Object.entries(attrs).filter(([key]) => key !== 'key'));
    return `{ tag: '${tag}', attrs: ${JSON.stringify(clean)} }`;
  });
  return `  // Lucide "${icon}"\n  ${name}: [\n    ${elements.join(',\n    ')},\n  ],`;
});

const source = `// Generated by scripts/generate-icons.mjs from ${pkg.name}@${pkg.version}. Do not edit by hand.
// Icons from Lucide (https://lucide.dev), ISC License, Copyright (c) Lucide Contributors.
import type { NodeIcon } from './schema.js';

export type IconElementTag = 'path' | 'rect' | 'circle' | 'ellipse' | 'line' | 'polyline' | 'polygon';

export interface IconElement {
  tag: IconElementTag;
  attrs: Record<string, string>;
}

/** Lucide line icons on a 24×24 grid, drawn with fill="none", round caps/joins and the node stroke. */
export const ICON_ELEMENTS: Record<NodeIcon, readonly IconElement[]> = {
${entries.join('\n')}
};

/** Lucide icon name used for each diagram icon (for apps that render them with lucide-react). */
export const LUCIDE_ICON_NAMES: Record<NodeIcon, string> = ${JSON.stringify(MAP, null, 2)};
`;
const out = new URL('../packages/kind-diagram/src/icons.ts', import.meta.url).pathname;
writeFileSync(out, source);
console.log(`Wrote ${Object.keys(MAP).length} Lucide icons to packages/kind-diagram/src/icons.ts`);
