import { z } from 'zod';
import { ArtifactError } from './errors.js';
import { t } from './i18n.js';

export const ASSET_REF_PATTERN = /^asset:\/\/[A-Za-z0-9][A-Za-z0-9_.-]{0,127}$/;

export const assetRefSchema = z
  .string()
  .regex(ASSET_REF_PATTERN, 'Use an asset reference like "asset://img_123" (register the file first).')
  .describe('Asset reference "asset://<id>". Binary files never go inside the JSON.');

export type AssetRef = string;

export function assetIdFromRef(ref: AssetRef): string {
  return ref.slice('asset://'.length);
}

export interface AssetMeta {
  mimeType: string;
  filename?: string;
  /** External URL the bytes came from, checked against the allowed domains. */
  sourceUrl?: string;
  /**
   * `upload` (default): bytes from users or models, validated by magic bytes and the MIME allowlist.
   * `generated`: files produced by artkit's own exporters (docx, xlsx, pptx…); only the size limit applies,
   * since their type is known and they are never rendered inline from the asset store.
   */
  origin?: 'upload' | 'generated';
}

export interface StoredAssetInfo {
  ref: AssetRef;
  mimeType: string;
  size: number;
  /** SHA-256 hex of the stored bytes. */
  hash: string;
  filename?: string;
}

export interface ResolvedAsset {
  bytes: Uint8Array;
  mimeType: string;
}

/** What exporters and renderers use to read assets; implemented on top of an AssetStore. */
export interface AssetResolver {
  resolve(ref: AssetRef): Promise<ResolvedAsset>;
}

export const DEFAULT_ALLOWED_MIME_TYPES = [
  'image/png',
  'image/jpeg',
  'image/webp',
  'image/gif',
  'image/svg+xml',
] as const;

export interface AssetPolicy {
  allowedMimeTypes: readonly string[];
  maxBytes: number;
  /** Size limit for files generated by exporters (`origin: 'generated'`); defaults to `maxBytes`. */
  maxGeneratedBytes?: number;
  /** Domains accepted for external URLs. Empty means external URLs are refused (spec §6.5). */
  allowedDomains: readonly string[];
}

export const defaultAssetPolicy: AssetPolicy = {
  allowedMimeTypes: DEFAULT_ALLOWED_MIME_TYPES,
  maxBytes: 10 * 1024 * 1024,
  maxGeneratedBytes: 50 * 1024 * 1024,
  allowedDomains: [],
};

/** Detects the real MIME type from magic bytes; never trusts the declared one alone. */
export function sniffMimeType(bytes: Uint8Array): string | undefined {
  const b = bytes;
  if (b.length >= 8 && b[0] === 0x89 && b[1] === 0x50 && b[2] === 0x4e && b[3] === 0x47) return 'image/png';
  if (b.length >= 3 && b[0] === 0xff && b[1] === 0xd8 && b[2] === 0xff) return 'image/jpeg';
  if (b.length >= 6 && b[0] === 0x47 && b[1] === 0x49 && b[2] === 0x46 && b[3] === 0x38) return 'image/gif';
  if (
    b.length >= 12 &&
    b[0] === 0x52 &&
    b[1] === 0x49 &&
    b[2] === 0x46 &&
    b[3] === 0x46 &&
    b[8] === 0x57 &&
    b[9] === 0x45 &&
    b[10] === 0x42 &&
    b[11] === 0x50
  )
    return 'image/webp';
  if (b.length >= 4 && b[0] === 0x25 && b[1] === 0x50 && b[2] === 0x44 && b[3] === 0x46)
    return 'application/pdf';
  const head = new TextDecoder().decode(b.slice(0, 512)).trimStart().toLowerCase();
  if (head.startsWith('<svg') || (head.startsWith('<?xml') && head.includes('<svg'))) return 'image/svg+xml';
  return undefined;
}

const SVG_FORBIDDEN = [
  /<script[\s\S]*?<\/script\s*>/gi,
  /<script[^>]*\/>/gi,
  /<foreignObject[\s\S]*?<\/foreignObject\s*>/gi,
  /<!ENTITY[^>]*>/gi,
  /<!DOCTYPE[^>]*>/gi,
  /<\?xml-stylesheet[^>]*\?>/gi,
];

/**
 * Sanitizes SVG bytes: removes scripts, foreign objects, entities, event handlers, javascript: URLs and
 * external references. Returns undefined when the result does not look like an SVG.
 */
export function sanitizeSvg(svg: string): string | undefined {
  let out = svg;
  for (const pattern of SVG_FORBIDDEN) out = out.replace(pattern, '');
  out = out.replace(/\s+on[a-z]+\s*=\s*("[^"]*"|'[^']*'|[^\s>]+)/gi, '');
  // href / xlink:href only to internal fragments or embedded raster data.
  out = out.replace(/\s+(xlink:)?href\s*=\s*("([^"]*)"|'([^']*)')/gi, (match, _ns, _quoted, dq, sq) => {
    const value = String(dq ?? sq ?? '').trim();
    return value.startsWith('#') || /^data:image\/(png|jpeg|gif|webp);base64,/i.test(value) ? match : '';
  });
  out = out.replace(/url\(\s*['"]?\s*(?!#)[^)]*\)/gi, 'none');
  out = out.replace(/javascript:/gi, '');
  out = out.replace(/@import[^;]*;?/gi, '');
  return /<svg[\s>]/i.test(out) ? out : undefined;
}

export interface CheckedAsset {
  bytes: Uint8Array;
  mimeType: string;
}

/** Validates bytes and metadata against the policy. Throws `ASSET_REJECTED` with the reason. */
export function checkAsset(
  bytes: Uint8Array,
  meta: AssetMeta,
  policy: AssetPolicy = defaultAssetPolicy,
  locale?: string,
): CheckedAsset {
  const reject = (reason: string): never => {
    throw new ArtifactError('ASSET_REJECTED', t(locale, 'ASSET_REJECTED', { reason }));
  };
  if (bytes.byteLength === 0) reject('empty file');
  if (meta.origin === 'generated') {
    const max = policy.maxGeneratedBytes ?? policy.maxBytes;
    if (bytes.byteLength > max) reject(`size ${bytes.byteLength} exceeds ${max} bytes`);
    if (!/^[a-z]+\/[a-z0-9.+-]+$/i.test(meta.mimeType)) reject(`invalid type ${meta.mimeType}`);
    return { bytes, mimeType: meta.mimeType };
  }
  if (bytes.byteLength > policy.maxBytes) reject(`size ${bytes.byteLength} exceeds ${policy.maxBytes} bytes`);
  if (meta.sourceUrl !== undefined && !isAllowedUrl(meta.sourceUrl, policy.allowedDomains)) {
    reject('external URL domain is not allowed');
  }
  const sniffed = sniffMimeType(bytes);
  if (!sniffed) reject('unrecognized file type');
  const mimeType = sniffed!;
  if (!policy.allowedMimeTypes.includes(mimeType)) reject(`type ${mimeType} is not allowed`);
  if (
    meta.mimeType &&
    meta.mimeType !== mimeType &&
    !(meta.mimeType === 'image/jpg' && mimeType === 'image/jpeg')
  ) {
    reject(`declared type ${meta.mimeType} does not match content ${mimeType}`);
  }
  if (mimeType === 'image/svg+xml') {
    const clean = sanitizeSvg(new TextDecoder().decode(bytes));
    if (!clean) reject('invalid SVG');
    return { bytes: new TextEncoder().encode(clean), mimeType };
  }
  return { bytes, mimeType };
}

export function isAllowedUrl(url: string, allowedDomains: readonly string[]): boolean {
  let parsed: URL;
  try {
    parsed = new URL(url);
  } catch {
    return false;
  }
  if (parsed.protocol !== 'https:') return false;
  const host = parsed.hostname.toLowerCase();
  return allowedDomains.some((domain) => {
    const d = domain.toLowerCase();
    return host === d || host.endsWith(`.${d}`);
  });
}

/** SHA-256 hex digest using Web Crypto (available in browsers, Node 22, edge and workers). */
export async function sha256Hex(bytes: Uint8Array): Promise<string> {
  const digest = await globalThis.crypto.subtle.digest('SHA-256', bytes as Uint8Array<ArrayBuffer>);
  return [...new Uint8Array(digest)].map((b) => b.toString(16).padStart(2, '0')).join('');
}

/** Encodes bytes as a data URL (used by headless render, which blocks the network). */
export function toDataUrl(bytes: Uint8Array, mimeType: string): string {
  let binary = '';
  for (let i = 0; i < bytes.length; i += 0x8000)
    binary += String.fromCharCode(...bytes.subarray(i, i + 0x8000));
  return `data:${mimeType};base64,${btoa(binary)}`;
}
